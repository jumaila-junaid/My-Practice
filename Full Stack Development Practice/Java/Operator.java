public class Operator {

    public static void main(String[] args) {
        int a = 10;
        int b = 5;

        System.out.println(a + b);

        System.out.println(a++);
        System.out.println(a);

        System.out.println(b += 5);
        System.out.println(b);

        int age = 5;

        boolean result = (age >= 18) ? true : false;
        System.out.println(result);

    }

}
